// Builds unicode-15.1.json, the code point tables of TAP-11 §3.5, from the
// Unicode Character Database 15.1.0.
//
// Usage:  node make-unicode-tables.mjs <ucd-dir> > unicode-15.1.json
// <ucd-dir> holds UnicodeData.txt, PropList.txt, DerivedCoreProperties.txt and
// DerivedNormalizationProps.txt from https://www.unicode.org/Public/15.1.0/ucd/
// and emoji-data.txt from .../15.1.0/ucd/emoji/. Nothing else is read.

import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = process.argv[2];
if (!dir) { console.error('usage: node make-unicode-tables.mjs <ucd-dir>'); process.exit(2); }
const read = (f) => readFileSync(join(dir, f), 'utf8');
const hex = (n) => n.toString(16).toUpperCase().padStart(4, '0');

function rangesOf(set) {
  const a = [...set].sort((x, y) => x - y), out = [];
  for (let i = 0; i < a.length;) {
    let j = i; while (j + 1 < a.length && a[j + 1] === a[j] + 1) j++;
    out.push(a[i] === a[j] ? hex(a[i]) : `${hex(a[i])}-${hex(a[j])}`); i = j + 1;
  }
  return out;
}
function propFile(text, wanted) {
  const sets = Object.fromEntries(wanted.map((w) => [w, new Set()]));
  for (const line of text.split('\n')) {
    const m = /^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*([A-Za-z_]+)/.exec(line);
    if (!m || !(m[3] in sets)) continue;
    // Derived files list a property once per line; value-less boolean properties only.
    if (/;\s*[A-Za-z_]+\s*;/.test(line.split('#')[0]) && m[3] !== 'Full_Composition_Exclusion') continue;
    for (let c = parseInt(m[1], 16); c <= parseInt(m[2] ?? m[1], 16); c++) sets[m[3]].add(c);
  }
  return sets;
}

const Cc = new Set(), Cf = new Set(), ccc = {}, decomp = {};
let first = null;
for (const line of read('UnicodeData.txt').split('\n')) {
  if (!line) continue;
  const f = line.split(';'), c = parseInt(f[0], 16);
  if (f[1].endsWith(', First>')) { first = c; continue; }
  const lo = f[1].endsWith(', Last>') ? first : c;
  for (let x = lo; x <= c; x++) {
    if (f[2] === 'Cc') Cc.add(x);
    if (f[2] === 'Cf') Cf.add(x);
  }
  if (f[3] !== '0') (ccc[f[3]] ??= new Set()).add(c);
  if (f[5] && !f[5].startsWith('<')) decomp[hex(c)] = f[5];
}
const di = propFile(read('DerivedCoreProperties.txt'), ['Default_Ignorable_Code_Point']);
const bc = propFile(read('PropList.txt'), ['Bidi_Control']);
const em = propFile(read('emoji-data.txt'), ['Emoji']);
const fce = propFile(read('DerivedNormalizationProps.txt'), ['Full_Composition_Exclusion']);

const out = {
  unicodeVersion: '15.1.0',
  note: 'Code point tables of TAP-11 section 3.5, generated by make-unicode-tables.mjs from the Unicode Character Database 15.1.0. A range is "XXXX" or "XXXX-YYYY" in hex. A code point in no range of a table does not have the property.',
  Cc: rangesOf(Cc), Cf: rangesOf(Cf),
  Default_Ignorable_Code_Point: rangesOf(di.Default_Ignorable_Code_Point),
  Bidi_Control: rangesOf(bc.Bidi_Control),
  Emoji: rangesOf(em.Emoji),
  Full_Composition_Exclusion: rangesOf(fce.Full_Composition_Exclusion),
  ccc: Object.fromEntries(Object.keys(ccc).sort((a, b) => a - b).map((k) => [k, rangesOf(ccc[k])])),
  decomposition: decomp,
};
process.stdout.write(JSON.stringify(out, null, 1).replace(/\[\n\s+([^\]]*?)\n\s+\]/gs, (m, body) => `[${body.replace(/\n\s+/g, ' ')}]`) + '\n');
