// ---------- §6, §7 signed answers (TAP-13 envelopes) ----------
function responseDigest({ container, id, method, params, ok, body, ts }) {
  const t = new Uint8Array(8); new DataView(t.buffer).setBigUint64(0, BigInt(ts))
  return keccak_256(concatBytes(utf8ToBytes('TAPI-1/resp/v2'), hexToBytes(strip(container)), k(id), k(canon({ method, params })), new Uint8Array([ok ? 1 : 0]), k(canon(body)), t))
}
