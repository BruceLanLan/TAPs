// Generates the test vectors of TAP-draft-payment-vouchers from the text of the draft.
// Self-contained: it needs only Node.js 20 or later and two packages from npm, at these exact versions
// (see package.json in this directory):
//   @noble/hashes 1.8.0   (Keccak-256)
//   @noble/curves 1.9.7   (secp256k1)
// Run:   npm install && node gen.mjs
// It writes conversion.json, voucher.json, envelopes.json and rate-source.json next to itself.
// Keys are published test keys; they hold nothing. The settlement contract and pool addresses are test values.
import { writeFileSync } from 'node:fs'
import { keccak_256 } from '@noble/hashes/sha3'
import { bytesToHex, concatBytes, hexToBytes, utf8ToBytes } from '@noble/hashes/utils'
import { secp256k1 } from '@noble/curves/secp256k1'

const out = (name, obj) => { writeFileSync(new URL(name, import.meta.url), JSON.stringify(obj, null, 2) + '\n'); console.log('wrote ' + name) }
const note = 'Generated by gen.mjs in this directory. Every field is an input or an expected output.'
const hex = (b) => '0x' + bytesToHex(b)
const strip = (h) => (h.startsWith('0x') ? h.slice(2) : h)

// ---------- primitives ----------
function address(pk) {
  const pub = secp256k1.getPublicKey(hexToBytes(strip(pk)), false)
  return checksum(bytesToHex(keccak_256(pub.subarray(1)).subarray(12)))
}
function checksum(a) { // EIP-55
  const lower = strip(a).toLowerCase(), h = bytesToHex(keccak_256(utf8ToBytes(lower)))
  return '0x' + [...lower].map((c, i) => (parseInt(h[i], 16) >= 8 ? c.toUpperCase() : c)).join('')
}
const word = (n) => hexToBytes(BigInt(n).toString(16).padStart(64, '0'))
const addrWord = (a) => hexToBytes(strip(a).toLowerCase().padStart(64, '0'))
const N = secp256k1.CURVE.n
function sign(digest, pk) { // low-s, v = 27 or 28
  const s = secp256k1.sign(digest, hexToBytes(strip(pk)), { lowS: true })
  const o = new Uint8Array(65); o.set(s.toCompactRawBytes()); o[64] = 27 + s.recovery; return hex(o)
}
// Recovery with the checks of TAP-13 §5 and of the draft's §3.1 (v MUST be 27 or 28 in a voucher).
function recover(digest, sigHex, { allowV01 }) {
  const b = hexToBytes(strip(sigHex)); if (b.length !== 65) return { refused: 'length' }
  let v = b[64]; if (v === 0 || v === 1) { if (!allowV01) return { refused: 'v' }; v += 27 }
  if (v !== 27 && v !== 28) return { refused: 'v' }
  const r = BigInt(hex(b.subarray(0, 32))), s = BigInt(hex(b.subarray(32, 64)))
  if (r < 1n || r >= N || s < 1n || s > N / 2n) return { refused: 'r-or-s' }
  const pub = new secp256k1.Signature(r, s).addRecoveryBit(v - 27).recoverPublicKey(digest).toRawBytes(false)
  return { address: checksum(bytesToHex(keccak_256(pub.subarray(1)).subarray(12))) }
}
// Canonical JSON (TAP-11 §6, RFC 8785) for the values used here: objects, arrays, strings, safe integers, booleans.
function canon(v) {
  if (v === null || typeof v === 'boolean') return JSON.stringify(v)
  if (typeof v === 'number') { if (!Number.isSafeInteger(v)) throw new Error('only safe integers here'); return String(v) }
  if (typeof v === 'string') return JSON.stringify(v)
  if (Array.isArray(v)) return '[' + v.map(canon).join(',') + ']'
  const keys = Object.keys(v).sort() // all keys here are ASCII, where UTF-16 order is code point order
  return '{' + keys.map((k) => JSON.stringify(k) + ':' + canon(v[k])).join(',') + '}'
}
const k = (s) => keccak_256(utf8ToBytes(s))

// ---------- §4.3 conversion ----------
const PRICE_RE = /^[0-9]+(\.[0-9]{1,8})?$/, RATE_RE = /^[0-9]+(\.[0-9]{1,18})?$/
function units(s, re, d) {
  if (typeof s !== 'string' || !re.test(s)) return null
  const [i, f = ''] = s.split('.'); return BigInt(i) * 10n ** BigInt(d) + BigInt((f + '0'.repeat(d)).slice(0, d))
}
const fmt8 = (n) => { const s = n.toString().padStart(9, '0'); return s.slice(0, -8) + '.' + s.slice(-8) }
function charge(priceUSD, rate, priceBEM) {
  const U = units(priceUSD, PRICE_RE, 8), R = units(rate, RATE_RE, 18), P = units(priceBEM, PRICE_RE, 8)
  if (U === null || U === 0n) return { error: 'priceUSD' }
  if (R === null || R === 0n) return { error: 'rate' }
  if (P === null || P === 0n) return { error: 'priceBEM' }
  const converted = (U * 10n ** 18n + R - 1n) / R
  const amount = converted < P ? converted : P
  return { U: U.toString(), R: R.toString(), P: P.toString(), converted: converted.toString(), charge: amount.toString(), capped: converted > P, usd: { currency: 'USD', amount: fmt8(U) }, bem: { currency: 'BEM', amount: fmt8(amount) } }
}
