// ---------- §4.5 reference rate ----------
const floorDiv = (a, b) => { const q = a / b; return a % b !== 0n && (a < 0n) !== (b < 0n) ? q - 1n : q }
function meanTick([c0, c1], window) { return floorDiv(BigInt(c1) - BigInt(c0), BigInt(window)) }
function refRate(t, { bemIsToken0, usdDecimals }) {
  const p = Math.pow(1.0001, Number(t))
  return bemIsToken0 ? p * 10 ** (8 - usdDecimals) : 1 / (p * 10 ** (usdDecimals - 8))
}
