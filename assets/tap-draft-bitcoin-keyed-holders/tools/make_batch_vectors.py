"""Builds vectors/batch-vectors.json and contracts/test/batch/GeneratedBatchVectors.sol for executeBatch
(TAP §5.3 and §6.4). Uses the public TEST keys of tools/cli.py (they hold nothing). Run after `forge build`.
If tools/wallet-lib-check/results-batch.json exists (node sign-batch.mjs, which reads the messages written
here), its bip322-js 4.0.0 signatures of the same messages are checked and included as well."""
import json
import os

import btc
import cli
import holder as H
from keccak import keccak256

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
TOKEN = bytes.fromhex("00000000000000000000000000000000000000c1")
RECIPIENT = bytes.fromhex("00000000000000000000000000000000000000b0")
DEADLINE = 2_000_000_000
CALL_GAS = 100_000
CHAIN = 56


def x(b):
    return "0x" + b.hex()


def transfer(holder, token_id):
    # safeTransferFrom(address,address,uint256)
    return (keccak256(b"safeTransferFrom(address,address,uint256)")[:4] + cli.w32(holder) + cli.w32(RECIPIENT)
            + cli.u256(token_id))


code = H.creation_code()
holders = {}
for kind in ("p2tr", "p2wpkh"):
    sk, spk = cli.test_key(kind)
    holders[kind] = (sk, spk, H.holder_address(spk, code))

cases = []


def add(name, kind, calls, tip, nonce=0, chain=CHAIN):
    sk, spk, h = holders[kind]
    msg = H.batch_message(h, chain, calls, tip, nonce, DEADLINE)
    assert H.parse_batch_message(msg) == (h, chain, [(t, v, keccak256(d), g) for t, v, d, g in calls], tip, nonce, DEADLINE)
    sig = btc.sign_simple(sk, spk, msg)
    assert btc.verify_simple(spk, msg, sig)
    cases.append({
        "name": name, "holder": kind, "chainId": chain, "tip": tip, "nonce": nonce, "deadline": DEADLINE,
        "calls": [{"target": x(t), "value": v, "data": x(d), "callGas": g} for t, v, d, g in calls],
        "message": msg.decode(), "messageLength": len(msg), "signature": x(sig),
        "calldata": x(cli.execute_batch_calldata(calls, tip, DEADLINE, sig)),
    })


for kind in ("p2tr", "p2wpkh"):
    h = holders[kind][2]
    for k in (1, 2, 3, 4, 5, 6, 7, 8):
        add(f"{kind}-{k}-transfers", kind, [(TOKEN, 0, transfer(h, i + 1), CALL_GAS) for i in range(k)], 0)
# a mixed batch with a tip: a token transfer, a plain coin transfer with callGas 0, another token transfer
h = holders["p2tr"][2]
add("p2tr-mixed-with-tip", "p2tr", [(TOKEN, 0, transfer(h, 1), CALL_GAS), (RECIPIENT, 10**15, b"", 0),
                                   (TOKEN, 0, transfer(h, 2), CALL_GAS)], 10**16)

# Signatures of the same messages made by bip322-js 4.0.0 (tools/wallet-lib-check/sign-batch.mjs).
lib_sigs = {}
lib_path = os.path.join(HERE, "wallet-lib-check", "results-batch.json")
if os.path.exists(lib_path):
    by_name = {c["name"]: c for c in cases}
    lib_rows = [r for r in json.load(open(lib_path))["cases"] if r["lib"] == "bip322-js@4.0.0" and r["name"] in by_name]
    if any(r["message"] != by_name[r["name"]]["message"] for r in lib_rows):
        # signed for an earlier build: leave them out (the test requires them, so this cannot pass unnoticed)
        print("results-batch.json is stale (other messages): bip322-js signatures left out; run sign-batch.mjs, then this again")
        lib_rows = []
    for r in lib_rows:
        c = by_name[r["name"]]
        spk = holders[c["holder"]][1]
        wit = btc.witness_from_wallet(r["signature"])
        assert btc.verify_simple(spk, c["message"].encode(), wit), r["name"]
        c["bip322js"] = {"library": r["lib"], "signature": r["signature"], "witness": x(wit),
                         "calldata": x(cli.execute_batch_calldata(
                             [(bytes.fromhex(k["target"][2:]), k["value"], bytes.fromhex(k["data"][2:]), k["callGas"])
                              for k in c["calls"]], c["tip"], DEADLINE, wit))}
        lib_sigs[r["name"]] = wit

out = {
    "format": "tap-bitcoin-keyed-holders-batch-vectors/1",
    "note": "Vectors for executeBatch (TAP §5.3, §6.4). TEST keys only; they must never be funded.",
    "creationCodeKeccak": x(keccak256(code)),
    "holders": {k: {"address": btc.segwit_address(1 if v[1][0] == 0x51 else 0, v[1][2:]), "scriptPubKey": x(v[1]),
                    "holder": x(v[2])} for k, v in holders.items()},
    "token": x(TOKEN), "recipient": x(RECIPIENT),
    "cases": cases,
}
with open(os.path.join(ROOT, "vectors", "batch-vectors.json"), "w") as f:
    json.dump(out, f, indent=1)
    f.write("\n")


def sol_bytes(b):
    return f'hex"{b.hex()}"'


idx = {"p2tr": 0, "p2wpkh": 1}
L = ["// SPDX-License-Identifier: MIT", "pragma solidity 0.8.28;",
     "// GENERATED by tools/make_batch_vectors.py from the same data as vectors/batch-vectors.json. Do not edit.", "",
     'import {BitcoinKeyedHolder as B} from "../../src/BitcoinKeyedHolder.sol";', "",
     "library GeneratedBatchVectors {",
     f"    bytes32 internal constant CREATION_CODE_KECCAK = {x(keccak256(code))};",
     f"    address internal constant TOKEN = address(bytes20(hex\"{TOKEN.hex()}\"));",
     f"    address internal constant RECIPIENT = address(bytes20(hex\"{RECIPIENT.hex()}\"));"]
for k, v in holders.items():
    L.append(f"    bytes internal constant SPK_{k.upper()} = {sol_bytes(v[1])};")
    L.append(f"    address internal constant HOLDER_{k.upper()} = address(bytes20(hex\"{v[2].hex()}\"));")
L.append("    struct BatchCase { string name; uint8 holder; uint256 chainId; uint256 tip; uint256 nonce; uint64 deadline; "
         "B.Call[] calls; bytes message; bytes sig; bytes calldata_; bytes libSig; }")
L.append(f"    function count() internal pure returns (uint256) {{ return {len(cases)}; }}")
L.append(f"    /// cases that also carry a bip322-js 4.0.0 signature (libSig): all or none")
L.append(f"    function libCount() internal pure returns (uint256) {{ return {len(lib_sigs)}; }}")
L.append("    function batchCase(uint256 i) internal pure returns (BatchCase memory c) {")
for i, c in enumerate(cases):
    L.append(f"        if (i == {i}) {{")
    L.append(f"            c.name = \"{c['name']}\"; c.holder = {idx[c['holder']]}; c.chainId = {c['chainId']}; c.tip = {c['tip']}; "
             f"c.nonce = {c['nonce']}; c.deadline = {c['deadline']};")
    L.append(f"            c.calls = new B.Call[]({len(c['calls'])});")
    for j, cl in enumerate(c["calls"]):
        L.append(f"            c.calls[{j}] = B.Call(address(bytes20(hex\"{cl['target'][2:]}\")), {cl['value']}, "
                 f"{sol_bytes(bytes.fromhex(cl['data'][2:]))}, {cl['callGas']});")
    L.append(f"            c.message = {sol_bytes(c['message'].encode())};")
    L.append(f"            c.sig = {sol_bytes(bytes.fromhex(c['signature'][2:]))};")
    L.append(f"            c.calldata_ = {sol_bytes(bytes.fromhex(c['calldata'][2:]))};")
    L.append(f"            c.libSig = {sol_bytes(lib_sigs.get(c['name'], b''))};")
    L.append("        }")
L.append("    }")
L.append("}")
with open(os.path.join(ROOT, "contracts", "test", "batch", "GeneratedBatchVectors.sol"), "w") as f:
    f.write("\n".join(L) + "\n")
print("batch vectors: %d cases (%d with bip322-js signatures), message lengths %s" % (
    len(cases), len(lib_sigs), [c["messageLength"] for c in cases]))
